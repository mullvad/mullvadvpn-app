//! GUIDs of every WFP object the Windows firewall registers.
//!
//! These must match `MullvadGuids` in `windows/winfw/src/winfw/mullvadguids.cpp` exactly.
//! Changing one means objects registered by an older version are never cleaned up.

use wfp::Guid;

/// Define the GUID constants of the objects the firewall installs, and
/// [`KNOWN_OBJECTS`], pairing each with its name.
macro_rules! known_guids {
    ($($name:ident = $value:literal;)*) => {
        $(pub const $name: Guid = Guid::from_u128($value);)*

        /// All objects with fixed GUIDs that the firewall installs, paired with
        /// their names.
        pub const KNOWN_OBJECTS: &[(&str, Guid)] = &[$((stringify!($name), $name)),*];
    };
}

