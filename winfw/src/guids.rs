/// Look up the name of a known WFP object GUID, for readable snapshots.
pub fn known_object_name(guid: &Guid) -> Option<&'static str> {
    KNOWN_OBJECTS
        .iter()
        .find(|(_, known)| known == guid)
        .map(|(name, _)| *name)
}
