import SwiftUI

/// Builds its content lazily, only when `body` is evaluated.
///
/// Use it in a `NavigationLink` destination so the view and its `@State`
/// view model are created on push instead of up front.
struct LazyView<Content: View>: View {
    private let build: () -> Content

    init(_ build: @autoclosure @escaping () -> Content) {
        self.build = build
    }

    var body: Content { build() }
}
